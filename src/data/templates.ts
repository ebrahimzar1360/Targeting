/** Adds the template's requirements to a freshly created plan. */
export function applyTemplate(plan: Plan, tpl: PlanTemplate): Plan {
  const cats = new Set(plan.categories.map((c) => c.id));
  return {
    ...plan,
    requirements: tpl.requirements
      .filter(([cat]) => cats.has(cat))
      .map(([cat, priority, title, desired]) => newRequirement(cat, { priority, title, desired })),
  };
}
